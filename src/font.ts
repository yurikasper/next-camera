export const GLYPH_WIDTH = 5;
export const GLYPH_HEIGHT = 7;

const GLYPHS: Record<string, string> = Object.fromEntries(
    Object.entries(GLYPH_ROWS).map(([char, rows]) => [char, rows.replace(/ /g, "")])
);

// Returns the glyph as a 35 character string, row by row
export function glyph(char: string): string {
    return GLYPHS[char.toUpperCase()] ?? GLYPHS[" "];
}

export function hasGlyph(char: string): boolean {
    return char.toUpperCase() in GLYPHS;
}

export function textWidth(text: string, scale: number): number {
    return text.length === 0 ? 0 : (text.length * (GLYPH_WIDTH + 1) - 1) * scale;
}
